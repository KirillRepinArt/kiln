// generate app/testing.js: in test mode (?test), window.kiln — the names the e2e tests read and write
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { createRequire } from "node:module";
import { join } from "node:path";

const require = createRequire(join(process.cwd(), "package.json"));
const espree = require("espree");
const owner = {};
for (const f of readdirSync("app").filter(f => f.endsWith(".js"))) {
  const ast = espree.parse(readFileSync("app/" + f, "utf8"), { ecmaVersion: "latest", sourceType: "module" });
  for (const st of ast.body) {
    const d = st.type === "ExportNamedDeclaration" ? st.declaration : null;
    if (!d) continue;
    if (d.type === "FunctionDeclaration") owner[d.id.name] = f;
    if (d.type === "VariableDeclaration")
      for (const x of d.declarations)
        JSON.stringify(x.id, (k, v) => (v && v.type === "Identifier" && k !== "key" && (owner[v.name] = f), v));
  }
}
// names the tests still use for state that moved: what they read now (and the module names that needs)
const ALIAS = {
  lyFrozen: { get: "card.frozen", uses: ["card", "lyUnfreeze"] },
  lyTop: { get: "card.top", uses: ["card"] },
  BAR: { get: "BAR()", uses: ["BAR"] }, // a function since the spacing tokens (the part gap is read from the CSS)
};
const names = JSON.parse(readFileSync("tools/dev/bridge-names.json", "utf8")).filter(n => owner[n] || ALIAS[n]);
// what a test may assign, and how the owner takes it
const SET = {
  draft: "setDraft",
  jobs: "replaceJobs",
  peekJob: "setPeekJob",
  justDone: "setJustDone",
  qsAnchor: "setQsAnchor",
};
const extra = [
  "setDraft",
  "replaceJobs",
  "setPeekJob",
  "setJustDone",
  "setQsAnchor",
  "lyUnfreeze",
  "blockSaves",
].filter(n => !names.includes(n));
const all = [
  ...new Set([...names.filter(n => !ALIAS[n]), ...extra, ...names.flatMap(n => (ALIAS[n] ? ALIAS[n].uses : []))]),
];
const byFile = {};
for (const n of all) (byFile[owner[n]] ||= []).push(n);
const imports = Object.entries(byFile)
  .sort()
  .map(([f, ns]) => `import { ${ns.sort().join(", ")} } from "./${f}";`)
  .join("\n");
const props = names
  .map(n => {
    const set = SET[n]
      ? `set: (/** @type {any} */ v) => ${SET[n]}(v)` // a test's value, whatever it set
      : n === "lyFrozen"
        ? 'set: (/** @type {any} */ v) => (v ? (() => { throw new Error("tests can only unfreeze"); })() : lyUnfreeze())'
        : n === "save"
          ? "set: () => blockSaves() /* a test replacing save = no more saves in this page */"
          : null;
    return `    ${n}: { get: () => ${ALIAS[n] ? ALIAS[n].get : n}${set ? ", " + set : ""} },`;
  })
  .join("\n");
writeFileSync(
  "app/testing.js",
  `// @ts-check
/* Kiln · the end-to-end tests' way in: with ?test in the address, window.kiln holds the names they read (and the few
   they set) — read live; a set goes through the owner. Nothing else is put on window. New tests write kiln.current();
   the older ones run their expressions inside kiln's scope (tools/tests/run.mjs). Generated by
   tools/dev/make-test-bridge.mjs. */
${imports}

export function installTestBridge() {
  const props = {
${props}
  };
  window.kiln = Object.defineProperties({}, Object.fromEntries(Object.entries(props).map(([n, p]) => [n, { ...p, enumerable: true }])));
}
`,
);
console.log(`testing.js: ${names.length} names from ${Object.keys(byFile).length} files`);
