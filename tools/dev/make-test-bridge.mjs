// generate app/testing.js: in test mode (?test), the names the e2e tests read and write, on window again
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { createRequire } from "node:module";
import { join } from "node:path";

const require = createRequire(join(process.cwd(), "package.json"));
const espree = require("espree");
const owner = {};
for (const f of readdirSync("app").filter(f => f.endsWith(".js"))) {
  const ast = espree.parse(readFileSync("app/" + f, "utf8"), { ecmaVersion: "latest", sourceType: "module" });
  for (const st of ast.body) {
    const d = st.type === "ExportNamedDeclaration" ? st.declaration : null;
    if (!d) continue;
    if (d.type === "FunctionDeclaration") owner[d.id.name] = f;
    if (d.type === "VariableDeclaration")
      for (const x of d.declarations)
        JSON.stringify(x.id, (k, v) => (v && v.type === "Identifier" && k !== "key" && (owner[v.name] = f), v));
  }
}
const names = JSON.parse(readFileSync("tools/dev/bridge-names.json", "utf8")).filter(n => owner[n]);
// what a test may assign, and how the owner takes it
const SET = {
  draft: "setDraft",
  jobs: "setJobs",
  peekJob: "setPeekJob",
  justDone: "setJustDone",
  qsAnchor: "setQsAnchor",
};
const extra = ["setDraft", "setJobs", "setPeekJob", "setJustDone", "setQsAnchor", "lyUnfreeze", "blockSaves"].filter(
  n => !names.includes(n),
);
const all = [...names, ...extra];
const byFile = {};
for (const n of all) (byFile[owner[n]] ||= []).push(n);
const imports = Object.entries(byFile)
  .sort()
  .map(([f, ns]) => `import { ${ns.sort().join(", ")} } from "./${f}";`)
  .join("\n");
const props = names
  .map(n => {
    const set = SET[n]
      ? `set: v => ${SET[n]}(v)`
      : n === "lyFrozen"
        ? 'set: v => (v ? (() => { throw new Error("tests can only unfreeze"); })() : lyUnfreeze())'
        : n === "save"
          ? "set: () => blockSaves() /* a test replacing save = no more saves in this page */"
          : null;
    return `    ${n}: { get: () => ${n}${set ? ", " + set : ""} },`;
  })
  .join("\n");
writeFileSync(
  "app/testing.js",
  `/* Kiln · the end-to-end tests' way in: with ?test in the address, the names they read (and the few they set) are put
   back on window, as before the page became ES modules. Values are read live; a set goes through the owner.
   Generated by tools/dev/to-modules.mjs's companion; goes away when the tests use a kiln.* handle (v0.7 step 4e). */
${imports}

export function installTestBridge() {
  const props = {
${props}
  };
  for (const [name, p] of Object.entries(props)) Object.defineProperty(window, name, { ...p, configurable: true });
}
`,
);
console.log(`testing.js: ${names.length} names from ${Object.keys(byFile).length} files`);
